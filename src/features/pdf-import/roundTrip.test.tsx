const readBack = async (cv: CVData, language: ResumeLocale) => {
  await i18next.changeLanguage(language);
  const buffer = await renderToBuffer(<CVDocument data={{ ...cv, locale: language }} />);
  const task = getDocument({ data: new Uint8Array(buffer), verbosity: VerbosityLevel.ERRORS });
  const content = await extractPdfContent(await task.promise);
  await task.destroy();
  let id = 0;
  return parseResume(content, () => `id-${++id}`);
};

const withoutIds = <T extends { id: string }>(items: T[] = []) => items.map((item) => ({ ...item, id: '' }));

const plainUrl = (url?: string) => (url ?? '').replace(/^https?:\/\//, '').replace(/^www\./, '').replace(/\/$/, '');

beforeAll(async () => {
  await i18next.use(initReactI18next).init({
    lng: 'pt-BR',
    showSupportNotice: false,
    resources: { 'pt-BR': { translation: ptBR }, en: { translation: en } },
  });
});

describe.each(['pt-BR', 'en'] as const)('PDF generated by the app (%s)', (language) => {
  it('reads every field back', async () => {
    const { cv, unmatched } = await readBack(fullCV, language);

    expect(unmatched).toEqual([]);
    expect(cv.fullName).toBe(fullCV.fullName);
    expect(cv.jobTitle).toBe(fullCV.jobTitle);
    expect(cv.email).toBe(fullCV.email);
    expect(cv.phone).toBe(fullCV.phone);
    expect(cv.address).toBe(fullCV.address);
    expect(plainUrl(cv.linkedin)).toBe(plainUrl(fullCV.linkedin));
    expect(cv.linkedinName).toBe(fullCV.linkedinName);
    expect(plainUrl(cv.github)).toBe(plainUrl(fullCV.github));
    expect(cv.githubName).toBe('');
    expect(plainUrl(cv.portfolio)).toBe(plainUrl(fullCV.portfolio));
    expect(cv.portfolioName).toBe(fullCV.portfolioName);
    expect(cv.objective).toBe(fullCV.objective);

    expect(withoutIds(cv.experience)).toEqual(withoutIds(fullCV.experience));
    expect(withoutIds(cv.education)).toEqual(withoutIds(fullCV.education));
    expect(withoutIds(cv.projects)).toEqual(withoutIds(fullCV.projects));
    expect(cv.skills).toBe(fullCV.skills);
    expect(cv.languages).toBe(fullCV.languages);
    expect(cv.softSkills).toBe(fullCV.softSkills);
    expect(cv.interpersonalSkills).toBe(fullCV.interpersonalSkills);
    expect(withoutIds(cv.references)).toEqual(withoutIds(fullCV.references));
  }, 30_000);
});

it('writes section titles in the resume language, not the interface language', async () => {
  await i18next.changeLanguage('pt-BR');
  const buffer = await renderToBuffer(<CVDocument data={{ ...fullCV, locale: 'en' }} />);
  const task = getDocument({ data: new Uint8Array(buffer), verbosity: VerbosityLevel.ERRORS });
  const content = await extractPdfContent(await task.promise);
  await task.destroy();
  const text = content.lines.map((line) => line.text);

  expect(text).toContain(en.pdf.experience);
  expect(text).not.toContain(ptBR.pdf.experience);
}, 30_000);

it('reads the sample resume that ships with the app, across two pages', async () => {
  const { cv, unmatched } = await readBack(defaultCV, 'pt-BR');

  expect(unmatched).toEqual([]);
  expect(cv.locale).toBe('pt-BR');
  expect(cv.fullName).toBe(defaultCV.fullName);
  expect(cv.experience.map((item) => [item.role, item.company, item.startDate, item.endDate])).toEqual(
    defaultCV.experience.map((item) => [item.role, item.company, item.startDate, item.endDate]),
  );
  expect(cv.experience.map((item) => item.description)).toEqual(defaultCV.experience.map((item) => item.description));
  expect(cv.projects?.map((item) => [item.name, item.link])).toEqual(
    defaultCV.projects?.map((item) => [item.name, item.link]),
  );
  expect(cv.interpersonalSkills).toBe(
    defaultCV.interpersonalSkills
      ?.split('\n')
      .map((line) => line.trim())
      .filter(Boolean)
      .join('\n'),
  );
}, 30_000);
